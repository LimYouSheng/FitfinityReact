test('content UI reconciles a real committed write whose HTTP response is interrupted', async ({ page }) => {
  const key = `interrupted/${randomUUID()}`, title = `Interrupted ${randomUUID()}`
  // Discard the genuine response at the client transport boundary. Service-worker
  // requests bypass Playwright route interception on WebKit, so wrap native fetch.
  await page.addInitScript(() => {
    const original = window.fetch.bind(window)
    window.__lostContentResponse = { writes: 0 }
    window.fetch = async (url, options) => {
      const target = new URL(typeof url === 'string' ? url : url.url, location.href)
      const mutation = target.pathname === '/api/content' && options?.method === 'POST'
      if (mutation) window.__lostContentResponse.writes++
      const response = await original(url, options)
      if (mutation && response.status === 200) {
        window.__lostContentResponse.committed = await response.clone().json()
        window.__lostContentResponse.requestKey = new Headers(options.headers).get('Idempotency-Key')
        throw new TypeError('Test transport discarded the committed response')
      }
      return response
    }
  })
  await signIn(page, 'owner', account('interrupted'))
  await page.goto('/#/content/new')
  await page.getByLabel('Content title', { exact: true }).fill(title)
  await page.getByLabel('Content key', { exact: true }).fill(key)
  await page.getByLabel('Content body', { exact: true }).fill('Retained after transport interruption')
  await page.getByRole('button', { name: 'Save Content', exact: true }).click()
  await page.getByRole('dialog', { name: 'Save content?', exact: true }).getByRole('button', { name: 'Save Content', exact: true }).click()
  await page.getByRole('button', { name: 'Check Content Save', exact: true }).click()
  const { committed, requestKey, writes } = await page.evaluate(() => window.__lostContentResponse)
  await expect(page).toHaveURL(new RegExp(`#/content/${committed.id}$`))
  expect(writes).toBe(1)
  expect(await read(page, `/api/content-saves/${requestKey}`)).toEqual(committed)
  await page.reload()
  await expect(page.getByLabel('Content body', { exact: true })).toHaveValue(committed.body)
  expect((await read(page, '/api/content')).filter(row => row.key === key)).toEqual([committed])
})

