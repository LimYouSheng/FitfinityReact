import { randomUUID } from 'node:crypto'
import { test, expect, signIn, read, account, freshContext } from './fixtures.js'

async function openApprovals(page) {
  const tab = page.getByRole('button', { name: 'Approval Requirements', exact: true })
  await expect(page.getByRole('heading', { name: 'adminapproval admin', exact: true })).toBeVisible()
  if (!await tab.isVisible()) await page.locator('.profile-menu > summary').click()
  await tab.click()
}

test('Owner policy and approval persist through real API while Admin proposal leaves content unchanged', async ({ page, browser }) => {
  await signIn(page, 'owner', account('adminapproval'))
  const admin = (await read(page, '/api/staff/admins')).find(row => row.details.email === account('adminapproval', 'admin'))
  expect(admin).toBeTruthy()
  await page.goto(`/#/admins/${admin.id}`)
  await openApprovals(page)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Manage content', exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('dialog', { name: 'Save changes?', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
  await page.reload()
  await openApprovals(page)
  await expect(page.getByRole('checkbox', { name: 'Manage content', exact: true })).toBeChecked()
  const context = await freshContext(browser, page)
  try {
    const adminPage = await context.newPage()
    await signIn(adminPage, 'admin', account('adminapproval', 'admin'))
    const key = `approval/${randomUUID()}`, title = `Reviewed ${randomUUID()}`
    await adminPage.goto('/#/content/new')
    await adminPage.getByLabel('Content title', { exact: true }).fill(title)
    await adminPage.getByLabel('Content key', { exact: true }).fill(key)
    await adminPage.getByLabel('Content body', { exact: true }).fill('Frozen proposal for Owner review')
    await adminPage.getByRole('button', { name: 'Save Content', exact: true }).click()
    await adminPage.getByRole('dialog', { name: 'Save content?', exact: true }).getByRole('button', { name: 'Save Content', exact: true }).click()
    await expect(adminPage.getByRole('main').getByRole('status').filter({ hasText: 'No changes have been applied.' })).toBeVisible()
    expect((await read(adminPage, '/api/content')).some(row => row.key === key)).toBe(false)
    await adminPage.reload()
    expect((await read(adminPage, '/api/admin-requests')).filter(row => row.body.body.draft.key === key)).toHaveLength(1)
    await page.goto('/#/messages')
    await page.getByRole('button', { name: 'Review', exact: true }).click()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(page.getByText('Frozen proposal for Owner review', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Approve', exact: true }).click()
    await page.getByRole('dialog', { name: 'Approve?', exact: true }).getByRole('button', { name: 'Approve', exact: true }).click()
    await expect(page.getByText('adminapproval admin · approved', { exact: true })).toBeVisible()
    await adminPage.goto('/#/messages')
    await adminPage.getByRole('button', { name: 'Review', exact: true }).click()
    await expect(adminPage.getByText('adminapproval admin · approved', { exact: true })).toBeVisible()
    const saved = (await read(adminPage, '/api/content')).find(row => row.key === key)
    expect(saved).toMatchObject({ title, body: 'Frozen proposal for Owner review', version: 1 })
    await adminPage.goto(`/#/content/${saved.id}`)
    await adminPage.reload()
    await expect(adminPage.getByLabel('Content body', { exact: true })).toHaveValue(saved.body)
  } finally { await context.close() }
})

test('package catalogue approval applies reviewed terms once and persists after reload', async ({ page, browser }) => {
  await signIn(page, 'owner', account('admincatalogue'))
  const admin = (await read(page, '/api/staff/admins')).find(row => row.details.email === account('admincatalogue', 'admin'))
  await page.goto(`/#/admins/${admin.id}`)
  await expect(page.getByRole('heading', { name: 'admincatalogue admin', exact: true })).toBeVisible()
  const tab = page.getByRole('button', { name: 'Approval Requirements', exact: true })
  if (!await tab.isVisible()) await page.locator('.profile-menu > summary').click()
  await tab.click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Manage the package catalogue', exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('dialog', { name: 'Save changes?', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
  const context = await freshContext(browser, page)
  try {
    const adminPage = await context.newPage()
    await signIn(adminPage, 'admin', account('admincatalogue', 'admin'))
    const name = `Reviewed package ${randomUUID()}`
    await adminPage.goto('/#/packages/new')
    await adminPage.getByLabel('Package name', { exact: true }).fill(name)
    await adminPage.getByLabel('Package session count', { exact: true }).fill('18')
    await adminPage.getByRole('button', { name: 'Create Package', exact: true }).click()
    await adminPage.getByRole('dialog', { name: 'Create Package?', exact: true }).getByRole('button', { name: 'Create Package', exact: true }).click()
    await expect(adminPage.getByRole('main').getByRole('status').filter({ hasText: 'No changes have been applied.' })).toBeVisible()
    expect((await read(adminPage, '/api/directory')).packages.some(row => row.name === name)).toBe(false)
    await page.goto('/#/messages')
    const row = page.locator('.info-row').filter({ hasText: 'admincatalogue admin' }).filter({ hasText: 'pending' })
    await row.getByRole('button', { name: 'Review', exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
    await expect(page.getByText('18 sessions · active', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Approve', exact: true }).click()
    await page.getByRole('dialog', { name: 'Approve?', exact: true }).getByRole('button', { name: 'Approve', exact: true }).click()
    await expect(page.getByText('admincatalogue admin · approved', { exact: true })).toBeVisible()
    const rows = (await read(adminPage, '/api/directory')).packages.filter(row => row.name === name)
    expect(rows).toHaveLength(1)
    expect(rows[0]).toMatchObject({ total_sessions: 18, validity_days: 135, version: 1 })
    await adminPage.goto(`/#/packages/${rows[0].id}`)
    await adminPage.reload()
    await expect(adminPage.getByRole('heading', { name, exact: true })).toBeVisible()
    await expect(adminPage.getByText('135 days', { exact: true })).toBeVisible()
  } finally { await context.close() }
})


test('Admin package proposal applies its reviewed schedule once and preserves the existing purchase', async ({ page, browser }, info) => {
  await signIn(page, 'owner', account('adminpurchase'))
  const admin = (await read(page, '/api/staff/admins')).find(row => row.details.email === account('adminpurchase', 'admin'))
  await page.goto(`/#/admins/${admin.id}`)
  await expect(page.getByRole('heading', { name: 'adminpurchase admin', exact: true })).toBeVisible()
  const tab = page.getByRole('button', { name: 'Approval Requirements', exact: true })
  if (!await tab.isVisible()) await page.locator('.profile-menu > summary').click()
  await tab.click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Add or manage purchased packages', exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('dialog', { name: 'Save changes?', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
  const context = await freshContext(browser, page)
  try {
    const adminPage = await context.newPage()
    await signIn(adminPage, 'admin', account('adminpurchase', 'admin'))
    const before = await read(adminPage, '/api/directory')
    const client = before.clients.find(row => row.name === `${info.project.name} adminpurchase`)
    await adminPage.goto(`/#/clients/${client.id}`)
    await expect(adminPage.getByRole('heading', { name: client.name, exact: true })).toBeVisible()
    const menu = adminPage.locator('details.profile-menu')
    if (await menu.locator('summary').isVisible() && await menu.getAttribute('open') === null) await menu.locator('summary').click()
    await menu.getByRole('button', { name: 'Package', exact: true }).click()
    await adminPage.getByRole('button', { name: 'Add Package', exact: true }).click()
    // Overlapping validity is allowed, but the existing two weekly bookings remain occupied.
    const start = new Date(`${client.purchases[0].start_date}T00:00:00Z`)
    start.setUTCDate(start.getUTCDate() + 14)
    await adminPage.getByLabel('Start date', { exact: true }).fill(start.toISOString().slice(0, 10))
    await adminPage.getByRole('button', { name: 'Continue to Client Availability', exact: true }).click()
    await adminPage.getByRole('button', { name: 'Continue to Trainer Matching', exact: true }).click()
    await expect(adminPage.getByLabel('Matched trainer', { exact: true })).toHaveValue(client.trainer_id)
    await adminPage.getByRole('button', { name: 'Continue to Review & Confirm', exact: true }).click()
    await adminPage.getByRole('dialog', { name: 'Add Package', exact: true }).getByRole('button', { name: 'Add Package', exact: true }).click()
    await adminPage.getByRole('dialog', { name: `Add package for ${client.name}?`, exact: true }).getByRole('button', { name: 'Add Package', exact: true }).click()
    await expect(adminPage.getByRole('dialog', { name: 'Add Package', exact: true })).toContainText('Submitted for Owner approval. No changes have been applied.')
    expect((await read(adminPage, '/api/directory')).clients.find(row => row.id === client.id).purchases).toEqual(client.purchases)
    const proposals = (await read(adminPage, '/api/admin-requests')).filter(row => row.operation === 'client.purchase')
    expect(proposals).toHaveLength(1)
    await page.goto('/#/messages')
    await page.locator('.info-row').filter({ hasText: 'adminpurchase admin' }).filter({ hasText: 'pending' }).getByRole('button', { name: 'Review', exact: true }).click()
    await page.getByRole('button', { name: 'Approve', exact: true }).click()
    await page.getByRole('dialog', { name: 'Approve?', exact: true }).getByRole('button', { name: 'Approve', exact: true }).click()
    await expect(page.getByText('adminpurchase admin · approved', { exact: true })).toBeVisible()
    await adminPage.reload()
    const after = await read(adminPage, '/api/directory')
    const saved = after.clients.find(row => row.id === client.id)
    expect(saved.purchases).toHaveLength(2)
    expect(saved.purchases.find(row => row.id === client.purchases[0].id)).toEqual(client.purchases[0])
    expect(saved.purchases.find(row => row.id !== client.purchases[0].id)).toMatchObject({ trainer_id: client.trainer_id, used: 0 })
    expect(after.clients.filter(row => row.id !== client.id)).toEqual(before.clients.filter(row => row.id !== client.id))
  } finally { await context.close() }
})
