test('M3 owner creates a trainer with rates, phone, availability, controls, identity and routed messages', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await begin(page)
  await page.getByLabel('Trainer phone country code', { exact: true }).selectOption('+60')
  await page.getByLabel('Trainer phone number', { exact: true }).fill('123456789')
  await next(page, 'Training & Rates')
  await page.getByLabel('Peak session rate', { exact: true }).fill('85.50')
  await page.getByLabel('Off-peak session rate', { exact: true }).fill('60')
  await next(page, 'Trainer Availability')
  await block(page)
  await next(page, 'Owner Approval Needed')
  for (const name of ['Availability changes', 'Session time changes', 'Trainer reassignment', 'Fixed weekly schedule changes']) {
    await expect(page.getByRole('checkbox', { name, exact: true })).toBeChecked()
  }
  await page.getByRole('checkbox', { name: 'Session time changes', exact: true }).uncheck()
  await confirm(page, 'M3 New Trainer')
  await expect(page.getByRole('heading', { name: 'M3 New Trainer', level: 1, exact: true })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Leave this edit?', exact: true })).toHaveCount(0)
  const result = await saved(page)
  expect(result.count).toBe(1)
  expect(result.trainer).toMatchObject({ phone: '+60 123456789', birthday: '', rates: { peak: 85.5, offPeak: 60 }, status: 'active' })
  expect(result.trainer.availability.Sunday).toEqual([['10:00', '12:00']])
  expect(result.trainer.approvalNeeded.sessionTime).toBe(false)
  expect(result.user).toMatchObject({ role: 'trainer', status: 'active', trainerId: result.trainer.id })
  expect(result.messages).toHaveLength(2)
  expect(result.messages.every(message => message.read === false)).toBe(true)
  await tab(page, 'Availability')
  await expect(heading(page, 'Approved Availability')).toBeVisible()
  await expect(page.locator('.availability-block')).toContainText('10:00am–12:00pm')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'M3 New Trainer', level: 1, exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

