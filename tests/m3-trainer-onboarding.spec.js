import { expect, test, selectDemoIdentity } from './fixtures.js'

const KEY = 'fitfinity-m2-demo-db-v4'
const heading = (page, name) => page.getByRole('heading', { level: 2, name, exact: true })
const next = (page, name) => page.getByRole('button', { name: `Continue to ${name}`, exact: true }).click()
const back = (page, name) => page.getByRole('button', { name: `Back to ${name}`, exact: true }).click()

async function begin(page, name = 'M3 New Trainer', email = 'm3-trainer@example.com') {
  await page.goto('/#/trainers/new')
  await page.getByLabel('Trainer name', { exact: true }).fill(name)
  await page.getByLabel('Trainer email', { exact: true }).fill(email)
  await page.getByLabel('Trainer gender', { exact: true }).selectOption('Female')
  await page.getByLabel('Trainer type', { exact: true }).fill('Personal')
}
async function block(page, day = 'Sunday', from = '10:00', to = '12:00') {
  await page.getByRole('button', { name: day, exact: true }).click()
  await page.getByLabel('Availability from', { exact: true }).fill(from)
  await page.getByLabel('Availability to', { exact: true }).fill(to)
  await page.getByRole('button', { name: 'Add Time', exact: true }).click()
}
async function ready(page) {
  await next(page, 'Training & Rates')
  await next(page, 'Trainer Availability')
  await block(page)
  await next(page, 'Owner Approval Needed')
}
async function reviewTrainer(page) {
  if (!(await heading(page, 'Review & Confirm').isVisible())) await next(page, 'Review & Confirm')
  await expect(heading(page, 'Review & Confirm')).toBeVisible()
}
async function confirm(page, name) {
  await reviewTrainer(page)
  await page.getByRole('button', { name: 'Create Trainer', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: `Create ${name}?`, exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Create Trainer', exact: true }).click()
}
async function saved(page, email = 'm3-trainer@example.com') {
  return page.evaluate(({ key, email }) => {
    const state = JSON.parse(localStorage.getItem(key))
    const trainer = state.trainers.find(item => item.email === email)
    return { trainer, count: state.trainers.filter(item => item.email === email).length,
      user: state.users.find(item => item.trainerId === trainer.id),
      messages: state.messages.filter(item => item.trainerId === trainer.id) }
  }, { key: KEY, email })
}
async function tab(page, name) {
  const menu = page.locator('.profile-menu')
  await expect(menu).toBeVisible()
  if (await menu.locator('summary').isVisible()) await menu.locator('summary').click()
  await menu.getByRole('button', { name, exact: true }).click()
}
async function noOverflow(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0)
}

