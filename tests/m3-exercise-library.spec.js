import { expect, test } from '@playwright/test'
import { seed } from '../src/data/seed.js'
import { DEFAULT_EXERCISES } from '../src/app/exerciseCatalog.js'
const KEY = 'fitfinity-m2-demo-db-v4'
const movement = DEFAULT_EXERCISES[0]
async function start(page, route = 'exercises', custom = null) {
  const data = structuredClone(seed)
  data.sessions = [{ ...data.sessions[0], id: 'library-session', clientId: 'c1', trainerId: 't1', status: 'planned', date: '2099-09-06', from: '10:00', to: '11:00', exercisePlan: [{ id: 'historical', name: movement.name, weight: '10 kg', reps: '8', rounds: '2', rest: '60 sec', customDetails: [] }] }]
  if (custom) data.exerciseLibrary = custom
  await page.addInitScript(({ key, data }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(data)) }, { key: KEY, data })
  await page.goto(`/#/${route}`)
}
const readDb = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY)
const go = (page, path) => page.evaluate(path => { location.hash = `#/${path}` }, path)
const button = (page, name) => page.getByRole('button', { name, exact: true })
async function save(page, name) {
  await button(page, name).click()
  const dialog = page.getByRole('dialog', { name: `${name}?`, exact: true })
  await expect(dialog).toBeVisible()
  await button(dialog, name).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.library-form fieldset[disabled]')).toHaveCount(0)
  const errors = await page.locator('.library-form > [role="alert"]').allTextContents()
  expect(errors, `Exercise save failed: ${errors.join(' ')}`).toEqual([])
}
async function create(page, name = 'M3 Band Row') {
  await button(page, 'Add Exercise').click()
  await page.getByRole('textbox', { name: 'Exercise name', exact: true }).fill(name)
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption('Upper Body')
  await page.getByLabel('Description', { exact: true }).fill('Keep elbows close.')
  await save(page, 'Create Exercise')
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  return (await readDb(page)).exerciseLibrary.find(item => item.name === name)
}
const noOverflow = async page => expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)

test('M3 exercise creation and editing work when the browser does not expose randomUUID', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(crypto, 'randomUUID', { value: undefined, configurable: true })
  })
  await start(page)
  expect(await page.evaluate(() => typeof crypto.randomUUID)).toBe('undefined')
  const created = await create(page, 'M3 HTTP Preview')
  await button(page, 'Edit Exercise').click()
  await page.getByLabel('Description', { exact: true }).fill('Edited during device preview.')
  await save(page, 'Save Exercise')
  await expect(page.locator('.library-summary')).toContainText('Edited during device preview.')
  const db = await readDb(page)
  expect(db.exerciseLibrary.find(item => item.name === 'M3 HTTP Preview').id).toBe(created.id)
  expect(db.messages.filter(message => message.exerciseId === created.id)).toHaveLength(2)
})

