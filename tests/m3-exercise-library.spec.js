test('M3 exercise photo persists after refresh and can be replaced by a video then removed', async ({ page }) => {
  await start(page, 'exercises/new')
  await page.getByRole('textbox', { name: 'Exercise name', exact: true }).fill('M3 Reference')
  await page.getByLabel('Photo / video', { exact: true }).setInputFiles({ name: 'reference.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') })
  await expect(page.getByRole('img', { name: 'Exercise reference' })).toBeVisible()
  await save(page, 'Create Exercise')
  await expect(page.getByRole('heading', { name: 'M3 Reference' })).toBeVisible()
  await page.reload()
  const photo = page.getByRole('img', { name: 'Exercise reference' })
  await expect(photo).toBeVisible(); await expect.poll(() => photo.evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
  await button(page, 'Edit Exercise').click()
  await page.getByLabel('Photo / video', { exact: true }).setInputFiles('tests/fixtures/silent-one-second.webm')
  await save(page, 'Save Exercise')
  await expect(page.locator('.library-summary')).toContainText('silent-one-second.webm')
  await expect(page.locator('.library-media-preview video')).toHaveAttribute('src', /^blob:/)
  const record = (await readDb(page)).exerciseLibrary.find(item => item.name === 'M3 Reference')
  expect(record.media.type).toBe('video/webm')
  await button(page, 'Edit Exercise').click(); await button(page, 'Remove Attachment').click()
  await save(page, 'Save Exercise')
  await expect(page.locator('.library-summary')).toContainText('No attachment')
  expect((await readDb(page)).exerciseLibrary.find(item => item.id === record.id).media).toBeNull()
  await noOverflow(page)
})
